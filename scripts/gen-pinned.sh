#!/usr/bin/env bash
# Regenerate gate/pinned.lean.
#
# The pin list is enumerated FROM LEAN'S OWN ENVIRONMENT, not by parsing source.
# Six rounds of review broke earlier versions; the last two broke a hand-written
# list (`Pattern.or`, `Srt3`) and then a regex-derived one whose name pattern
# excluded dots and Greek letters, silently dropping `Model.Sat`, `AppCtx.plug`,
# `Γ3` and others. A coverage check written with the SAME regex reported
# "91 of 91" and was comparing the generator against itself.
#
# Asking the kernel which declarations exist removes that entire class: the list
# cannot omit what the environment contains.
set -uo pipefail
cd "$(dirname "$0")/.."
export PATH="$HOME/.elan/bin:$PATH"
ENUM=$(mktemp /tmp/mlenum-XXXXXX.lean); trap 'rm -f "$ENUM"' EXIT
cat > "$ENUM" <<'LEAN'
import MatchingLogic
open Lean in
run_cmd do
  let env ← getEnv
  let mut ds := #[]
  let mut is := #[]
  for (n, ci) in env.constants.toList do
    let s := n.toString
    unless s.startsWith "MatchingLogic" do continue
    if n.isInternal then continue
    if (s.splitOn "._").length > 1 then continue
    if s.endsWith ".rec" || s.endsWith ".recOn" || s.endsWith ".casesOn" || s.endsWith ".below"
       || s.endsWith ".brecOn" || s.endsWith ".brecOn.go" || s.endsWith ".ndrec" || s.endsWith ".ibelow"
       || s.endsWith ".binductionOn" || s.endsWith ".noConfusion" || s.endsWith ".noConfusionType"
       || s.endsWith ".sizeOf" || s.endsWith ".injEq" || s.endsWith ".inj" || s.endsWith ".eq_def"
       || s.endsWith ".mk" || s.endsWith ".toCtorIdx" || s.endsWith ".ofNat" || s.endsWith ".elim"
       || s.endsWith ".ctorIdx" || s.endsWith ".ctorElim" || s.endsWith ".ctorElimType" then continue
    match ci with
    | .defnInfo _ => ds := ds.push s
    | .inductInfo _ => is := is.push s
    | _ => pure ()
  for x in ds.qsort (· < ·) do IO.println s!"D {x}"
  for x in is.qsort (· < ·) do IO.println s!"I {x}"
LEAN
OUT=$(lake env lean "$ENUM" 2>/dev/null | grep -vE '\.(eq_[0-9]|match_[0-9]|proof_[0-9]|_sunfold|_unsafe_rec|_cstage)')
{
  echo "-- GENERATED by scripts/gen-pinned.sh from Lean's environment. Do not edit."
  echo "-- Every definition's body and every type's constructor set, plus the type"
  echo "-- of every certified statement. Coverage is not curated: it is whatever"
  echo "-- the kernel reports exists."
  echo "import MatchingLogic"
  echo ""
  echo "-- Definition BODIES. A weakened definition changes no type, and a theorem"
  echo "-- above it keeps both its statement and its proof."
  printf '%s\n' "$OUT" | awk '$1=="D"{print "#print " $2}'
  echo ""
  echo "-- CONSTRUCTOR SETS. A rule or syntactic form cannot be added, dropped or"
  echo "-- reshaped without the recursor's type changing."
  printf '%s\n' "$OUT" | awk '$1=="I"{print "#check @" $2 ".rec"}'
  echo ""
  echo "-- Every certified statement's TYPE."
  grep -vE '^#|^$' gate/certified.txt | sed 's/^/#check @/'
} > gate/pinned.lean
echo "gate/pinned.lean: $(grep -c '^#print' gate/pinned.lean) bodies, $(grep -c '^#check @.*\.rec$' gate/pinned.lean) constructor sets, $(grep -cvE '^#check @.*\.rec$' <(grep '^#check' gate/pinned.lean)) certified statements"
